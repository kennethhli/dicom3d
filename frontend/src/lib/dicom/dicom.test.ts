import { existsSync, readdirSync, readFileSync } from 'node:fs'
import path from 'node:path'
import { describe, expect, it } from 'vitest'
import { assembleVolume, toHalfFloat } from './assemble'
import { decodeBundle } from './bundle'
import { parseSlice } from './parse'

const SAMPLES = path.resolve(import.meta.dirname, '../../../../backend/data/samples')

function readSeries(id: string): ArrayBuffer[] {
  const dir = path.join(SAMPLES, id)
  return readdirSync(dir)
    .filter((f) => f.endsWith('.dcm'))
    .sort()
    .map((f) => {
      const buf = readFileSync(path.join(dir, f))
      return buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength)
    })
}

function halfToFloat(h: number): number {
  const e = (h >> 10) & 0x1f
  const m = h & 0x3ff
  const s = h & 0x8000 ? -1 : 1
  if (e === 0) return s * 2 ** -14 * (m / 1024)
  return s * 2 ** (e - 15) * (1 + m / 1024)
}

describe('bundle', () => {
  it('decodes length-prefixed files', () => {
    const bytes = new Uint8Array([0x44, 0x33, 0x44, 0x42, 1, 0, 0, 0, 2, 0, 0, 0, 1, 0, 0, 0, 7, 0, 0, 0, 0])
    const files = decodeBundle(bytes.buffer)
    expect(files.map((f) => f.byteLength)).toEqual([1, 0])
    expect(new Uint8Array(files[0])[0]).toBe(7)
  })

  it('rejects other payloads', () => {
    expect(() => decodeBundle(new Uint8Array(16).buffer)).toThrow(/bundle/)
  })
})

describe('toHalfFloat', () => {
  it('round-trips the normalised range within half precision', () => {
    const src = new Float32Array([0, 1e-6, 0.1, 0.25, 0.5, 0.7777, 1])
    const half = toHalfFloat(src)
    src.forEach((v, i) => expect(halfToFloat(half[i])).toBeCloseTo(v, 3))
  })
})

describe.skipIf(!existsSync(path.join(SAMPLES, 'hu-calibration')))('sample series (generated by the API)', () => {
  it('parses Hounsfield units with rescale slope/intercept', () => {
    const [first] = readSeries('hu-calibration')
    const slice = parseSlice(first, 0)
    expect(slice.modality).toBe('CT')
    expect(slice.rescaleIntercept).toBe(-1024)
    expect(slice.min).toBeGreaterThanOrEqual(-1024)
    expect(slice.pixelSpacing[0]).toBeCloseTo(1.1)
  })

  it('reconstructs a sorted volume with physical spacing', () => {
    const buffers = readSeries('hu-calibration').reverse()
    const slices = buffers.map((b, i) => parseSlice(b, i))
    const vol = assembleVolume(slices)
    expect(vol.dims).toEqual([192, 192, 64])
    expect(vol.spacing[2]).toBeCloseTo(2.5)
    expect(vol.metadata.sortedBy).toBe('position')

    const [nx, ny, nz] = vol.dims
    const centre = Math.floor(nz / 2) * nx * ny + Math.floor(ny / 2) * nx + Math.floor(nx / 2)
    const hu = vol.valueMin + vol.data[centre] * (vol.valueMax - vol.valueMin)
    expect(Math.abs(hu)).toBeLessThan(25)
    expect(vol.gpuData.length).toBe(vol.data.length)
  })

  it.skipIf(!existsSync(path.join(SAMPLES, 'chest-ct')))('assembles the chest phantom', () => {
    const slices = readSeries('chest-ct').map((b, i) => parseSlice(b, i))
    const t0 = performance.now()
    const vol = assembleVolume(slices)
    expect(vol.dims[2]).toBe(slices.length)
    expect(performance.now() - t0).toBeLessThan(5000)
  })
})
